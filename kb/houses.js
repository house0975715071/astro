const CN_NUM = Object.freeze(['', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十', '十一', '十二']);

export function houseName(n) {
  const i = Number(n);
  if (!Number.isInteger(i) || i < 1 || i > 12) throw new Error('宮位必須是 1 到 12 的整數');
  return `第${CN_NUM[i]}宮`;
}

